export function mapCountryCode(code: string, lang: 'en' | 'pl' = 'pl'): string {
  if (!code) return '';
  const upperCode = code.toUpperCase().trim();
  const mapping = COUNTRY_CODE_MAP[upperCode];
  if (!mapping) return code;

  if (lang === 'pl' && Array.isArray(mapping.pl)) {
    return mapping.pl[0];
  }

  // safe access with type narrowing if needed, but here simple property access is enough
  const val = mapping[lang];
  if (Array.isArray(val)) return val[0];
  return val || (Array.isArray(mapping.pl) ? mapping.pl[0] : mapping.pl) || code;
}
